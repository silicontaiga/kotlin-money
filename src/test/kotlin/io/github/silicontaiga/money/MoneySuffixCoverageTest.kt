class MoneySuffixCoverageTest : FunSpec({

    test("every shipped suffix is its currency's code, lowercased") {
        everySuffix.forAll { (money, code) -> money.currency.code shouldBe code }
    }

    test("the shipped suffixes cover a couple of dozen currencies") {
        everySuffix.map { it.second }.distinct().size shouldBe 28
    }
})
